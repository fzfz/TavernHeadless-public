import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {loadInspectionSections,listInspectionRecords} from '../shared/generation-inspection.prototype.js';
const config=JSON.parse(await fs.readFile(new URL('../shared/generation-inspection.config.json',import.meta.url)));
const calls=[];
const client={async request(path){calls.push(path);if(path.includes('memory/proposals'))throw Object.assign(Error('denied'),{code:'FORBIDDEN'});return path.includes('limit=')?{data:[{id:path}],meta:{has_more:false}}:{data:{path}};}};
const floor={id:'f',session_id:'s',state:'committed'};
const sections=await loadInspectionSections(client,floor,[{id:'p',page_no:0,messages:[{id:'m',seq:1}]}],config);
assert.equal(sections.length,config.floor.length+config.page.length+config.message.length);
assert(sections.find(x=>x.key==='p:memoryProposals').error);
assert(sections.find(x=>x.key==='tools').value.length===1);
assert(calls.includes('/sessions/s/role-view/floors/f'));
assert(calls.includes('/messages/m/manual-revisions'));
calls.length=0;
await loadInspectionSections(client,{...floor,state:'failed'},[],config);
assert(!calls.some(x=>x.includes('/explain')));
let count=0;assert.equal((await listInspectionRecords({request:async()=>({data:[++count],meta:{has_more:count===1}})},'/list?q=1')).length,2);
assert.deepEqual(await listInspectionRecords({request:async()=>({data:[],meta:{has_more:false}})},'/list'),[]);
await assert.rejects(()=>listInspectionRecords({request:async()=>{throw Error('fail')}},'/list'),/fail/);
console.log('inspection coverage, partial failure, pagination, empty, lifecycle and message revisions passed');
