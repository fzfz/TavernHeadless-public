import { writeFileSync } from "node:fs";
import { exportJsonSchema } from "./export-json-schema.js";
import { z } from "zod";
import {
  nativeCardPackageSchemas,
  nativeCardFileRulesSchema,
} from "../packages/shared/src/schemas/native-card-package/schema.js";
import {
  nativeCardSchema,
  nativeCardAllocateEntryUidSchema,
  nativeCardAllocateEntryUidResultSchema,
  nativeCardCreateSchema,
  nativeCardFileContentSchema,
  nativeCardSaveSchema,
  nativeCardValidationSchema,
  nativeCardImportSchema,
  nativeCardBuildSchema,
  nativeCardBuildRequestSchema,
  nativeCardPublishSchema,
  nativeCardPreviewSchema,
  nativeCardPreviewResultSchema,
  nativeCardPublicationSchema,
  nativeCardIdParamsSchema,
  nativeCardImportParamsSchema,
  nativeCardBuildParamsSchema,
  nativeCardRevisionQuerySchema,
  nativeCardFileQuerySchema,
  nativeCardImportQuerySchema,
} from "../packages/shared/src/schemas/native-card-api.js";
import { replaceRoleModelCapabilityJsonSchemas } from "./role-model-capability-json-schema.js";

const schemas = {
  nativeCardAllocateEntryUid: nativeCardAllocateEntryUidSchema,
  nativeCardAllocateEntryUidResponse: z.object({
    data: nativeCardAllocateEntryUidResultSchema,
  }),
  nativeCardResponse: z.object({ data: nativeCardSchema }),
  nativeCardListResponse: z.object({ data: z.array(nativeCardSchema) }),
  nativeCardFileResponse: z.object({ data: nativeCardFileContentSchema }),
  nativeCardValidationResponse: z.object({ data: nativeCardValidationSchema }),
  nativeCardImportResponse: z.object({ data: nativeCardImportSchema }),
  nativeCardBuildResponse: z.object({ data: nativeCardBuildSchema }),
  nativeCardPreviewResponse: z.object({ data: nativeCardPreviewResultSchema }),
  nativeCardPublicationResponse: z.object({
    data: nativeCardPublicationSchema,
  }),
  nativeCardCreate: nativeCardCreateSchema,
  nativeCardSave: nativeCardSaveSchema,
  nativeCardBuildRequest: nativeCardBuildRequestSchema,
  nativeCardPublish: nativeCardPublishSchema,
  nativeCardPreview: nativeCardPreviewSchema,
  nativeCardIdParams: nativeCardIdParamsSchema,
  nativeCardImportParams: nativeCardImportParamsSchema,
  nativeCardBuildParams: nativeCardBuildParamsSchema,
  nativeCardRevisionQuery: nativeCardRevisionQuerySchema,
  nativeCardFileQuery: nativeCardFileQuerySchema,
  nativeCardImportQuery: nativeCardImportQuerySchema,
};
writeFileSync(
  new URL(
    "../packages/shared/src/generated/native-card-json-schemas.ts",
    import.meta.url,
  ),
  "// Generated by scripts/generate-native-card-schemas.ts.\n" +
    (
      await Promise.all(
        Object.entries(schemas).map(
          async ([name, schema]) =>
            `export const ${name}JsonSchema = ${JSON.stringify(replaceRoleModelCapabilityJsonSchemas(await exportJsonSchema(schema)), null, 2)} as const;`,
        ),
      )
    ).join("\n") +
    "\n",
);

for (const [filename, schema] of Object.entries(nativeCardPackageSchemas)) {
  writeFileSync(
    new URL(
      `../packages/shared/src/schemas/native-card-package/${filename}`,
      import.meta.url,
    ),
    JSON.stringify(
      {
        ...(await exportJsonSchema(schema)),
        $comment:
          "Generated from schema.ts by scripts/generate-native-card-schemas.ts.",
      },
      null,
      2,
    ) + "\n",
  );
}
writeFileSync(
  new URL(
    "../packages/shared/src/config/native-card-file-rules.schema.json",
    import.meta.url,
  ),
  JSON.stringify(
    {
      ...(await exportJsonSchema(nativeCardFileRulesSchema)),
      $comment:
        "Generated from schemas/native-card-package/schema.ts by scripts/generate-native-card-schemas.ts.",
    },
    null,
    2,
  ) + "\n",
);
