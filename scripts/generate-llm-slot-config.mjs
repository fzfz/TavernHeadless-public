import { readFile, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";

const configPath = new URL("../packages/shared/src/config/llm-slots.json", import.meta.url);
const schemaPath = new URL("../packages/shared/src/config/llm-slots.schema.json", import.meta.url);
const outputPath = new URL("../packages/shared/src/generated/llm-slots.ts", import.meta.url);
const config = JSON.parse(await readFile(configPath, "utf8"));
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const validate = new Ajv2020({ allErrors: true, strict: true }).compile(schema);
if (!validate(config)) throw new Error(`Invalid LLM slot config: ${JSON.stringify(validate.errors)}`);
if (!config.instanceSlots.includes("*") || config.instanceSlots[0] !== "*") {
  throw new Error("LLM instance slots must start with the wildcard slot.");
}
for (const slot of config.modelSlots) {
  if (!config.instanceSlots.includes(slot) || slot === "*") throw new Error(`Model slot ${slot} must be a named instance slot.`);
}
for (const slot of config.defaultStateModelSlots) {
  if (!config.modelSlots.includes(slot) || slot === config.stateUpdaterSlot) {
    throw new Error(`Default state model slot ${slot} must be a non-updater model slot.`);
  }
}
if (!config.modelSlots.includes(config.stateUpdaterSlot)) {
  throw new Error("The state updater slot must be present in modelSlots.");
}
const body = `// Generated from config/llm-slots.json. Do not edit this file directly.\nexport const llmSlotConfig = ${JSON.stringify(config, null, 2)} as const;\nexport const llmInstanceSlots = llmSlotConfig.instanceSlots;\nexport const llmModelSlots = llmSlotConfig.modelSlots;\nexport const defaultStateModelSlots = llmSlotConfig.defaultStateModelSlots;\nexport const stateUpdaterSlot = llmSlotConfig.stateUpdaterSlot;\nexport type LlmModelSlot = (typeof llmModelSlots)[number];\n`;
await writeFile(outputPath, body);
