import { writeFileSync } from "node:fs";
import { exportJsonSchema } from "./export-json-schema.js";
import {
  modelCallDetailSchema,
  modelCallListSchema,
  modelCallQuerySchema,
} from "../packages/shared/src/schemas/model-call.js";

const schemas = {
  modelCallDetailJsonSchema: await exportJsonSchema(modelCallDetailSchema),
  modelCallListJsonSchema: await exportJsonSchema(modelCallListSchema),
  modelCallQueryJsonSchema: await exportJsonSchema(modelCallQuerySchema),
};
writeFileSync(
  new URL(
    "../packages/shared/src/generated/model-call-json-schemas.ts",
    import.meta.url,
  ),
  "// Generated by scripts/generate-model-call-schemas.ts.\n" +
    Object.entries(schemas)
      .map(
        ([name, schema]) =>
          `export const ${name} = ${JSON.stringify(schema, null, 2)} as const;\n`,
      )
      .join("\n"),
);
