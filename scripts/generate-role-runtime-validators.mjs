import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import Ajv from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const schemaDirectory = new URL("packages/shared/src/schemas/", root);
const ajv = new Ajv({ strict: true, code: { source: true, esm: true } });
const exports = {};

for (const [filename, prefix] of [
  ["runtime-policy.schema.json", ""],
  ["role-runtime.schema.json", ""],
  ["role-tool-evidence.schema.json", "roleTool"],
  ["role-model-capabilities.schema.json", "roleModel"],
  ["state-update.schema.json", "stateUpdate"],
  ["role-transport.schema.json", "transport"],
]) {
  const schema = JSON.parse(
    await readFile(new URL(filename, schemaDirectory), "utf8"),
  );
  ajv.addSchema(schema);
  for (const name of Object.keys(schema.definitions ?? {})) {
    const exportedName = prefix
      ? prefix + name[0].toUpperCase() + name.slice(1)
      : name === "package"
        ? "packageSchema"
        : name;
    exports[exportedName] = `${schema.$id}#/definitions/${name}`;
  }
}

const result = await build({
  stdin: {
    contents: standalone(ajv, exports),
    resolveDir: fileURLToPath(root),
  },
  bundle: true,
  format: "esm",
  platform: "browser",
  write: false,
});
const output = new URL(
  "packages/shared/src/generated/role-runtime-validators.ts",
  root,
);
await mkdir(new URL(".", output), { recursive: true });
await writeFile(
  output,
  "// @ts-nocheck\n// Generated by scripts/generate-role-runtime-validators.mjs.\n" +
    result.outputFiles[0].text,
);
