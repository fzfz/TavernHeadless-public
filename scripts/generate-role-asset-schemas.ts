import { writeFileSync } from "node:fs";
import { exportJsonSchema } from "./export-json-schema.js";
import {
  createRoleAssetsSchema,
  roleAssetUploadResultSchema,
  roleAssetVersionParamsSchema,
} from "../packages/shared/src/schemas/role-assets.js";

const schemas = {
  createRoleAssetsJsonSchema: await exportJsonSchema(createRoleAssetsSchema),
  roleAssetUploadResultJsonSchema: await exportJsonSchema(
    roleAssetUploadResultSchema,
  ),
  roleAssetVersionParamsJsonSchema: await exportJsonSchema(
    roleAssetVersionParamsSchema,
  ),
};
writeFileSync(
  new URL(
    "../packages/shared/src/generated/role-asset-json-schemas.ts",
    import.meta.url,
  ),
  "// Generated by scripts/generate-role-asset-schemas.ts.\n" +
    Object.entries(schemas)
      .map(
        ([name, schema]) =>
          `export const ${name} = ${JSON.stringify(schema, null, 2)} as const;\n`,
      )
      .join("\n"),
);
