import { writeFileSync } from "node:fs";
import { exportJsonSchema } from "./export-json-schema.js";
import { z } from "zod";
import {
  createRoleAppSchema,
  roleAppValidationSchema,
  updateRoleAppSchema,
  roleAppRevisionSchema,
  createRolePreviewSessionSchema,
  roleAppSchema,
  rolePreviewSessionSummarySchema,
  rolePreviewSessionCreatedSchema,
} from "../packages/shared/src/schemas/role-app.js";
import { replaceRoleModelCapabilityJsonSchemas } from "./role-model-capability-json-schema.js";

const schemas = {
  roleAppValidationResponse: z.object({ data: roleAppValidationSchema }),
  rolePreviewSessionCreatedResponse: z.object({
    data: rolePreviewSessionCreatedSchema,
  }),
  createRoleApp: createRoleAppSchema,
  updateRoleApp: updateRoleAppSchema,
  roleAppRevision: roleAppRevisionSchema,
  createRolePreviewSession: createRolePreviewSessionSchema,
  roleAppResponse: z.object({ data: roleAppSchema }),
  roleAppListResponse: z.object({ data: z.array(roleAppSchema) }),
  rolePreviewSessionListResponse: z.object({
    data: z.array(rolePreviewSessionSummarySchema),
  }),
};
writeFileSync(
  new URL(
    "../packages/shared/src/generated/role-app-json-schemas.ts",
    import.meta.url,
  ),
  "// Generated by scripts/generate-role-app-schemas.ts.\n" +
    (
      await Promise.all(
        Object.entries(schemas).map(
          async ([name, schema]) =>
            "export const " +
            name +
            "JsonSchema = " +
            JSON.stringify(
              replaceRoleModelCapabilityJsonSchemas(
                await exportJsonSchema(schema),
              ),
              null,
              2,
            ) +
            " as const;",
        ),
      )
    ).join("\n") +
    "\n",
);
