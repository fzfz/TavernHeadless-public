import { writeFileSync } from "node:fs";
import { exportJsonSchema } from "./export-json-schema.js";
import * as schemas from "../packages/shared/src/schemas/role-view.js";
import {
  roleStateUpdateRequestSchema,
  roleStateProposalInspectionInputSchema,
  roleStateProposalInspectionResponseSchema,
} from "../packages/shared/src/schemas/role-state.js";
import * as statePromptSchemas from "../packages/shared/src/schemas/state-prompt-preview.js";
import * as repairSchemas from "../packages/shared/src/schemas/role-state-repair.js";
import {
  stateContractParamsSchema,
  stateContractResponseSchema,
} from "../packages/shared/src/schemas/role-migration.js";
import {
  roleMessagesQuerySchema,
  roleMessagesSchema,
} from "../packages/shared/src/schemas/preset-output.js";
import { z } from "zod";
const contracts = {
  ...schemas,
  statePromptDryRunRequestSchema:
    statePromptSchemas.statePromptDryRunRequestSchema,
  statePromptPreviewResponseSchema:
    statePromptSchemas.statePromptPreviewResponseSchema,
  ...Object.fromEntries(
    Object.entries(repairSchemas).filter(([name]) => name.endsWith("Schema")),
  ),
  roleStateUpdateRequestSchema,
  roleStateProposalInspectionInputSchema,
  roleStateProposalInspectionResponseSchema,
  stateContractParamsSchema,
  stateContractResponseSchema: z.object({ data: stateContractResponseSchema }),
  roleMessagesQuerySchema,
  roleMessagesResponseSchema: z.object({ data: roleMessagesSchema }),
};
writeFileSync(
  new URL(
    "../packages/shared/src/generated/role-view-json-schemas.ts",
    import.meta.url,
  ),
  "// Generated by scripts/generate-role-view-schemas.ts.\n" +
    (
      await Promise.all(
        Object.entries(contracts).map(
          async ([name, schema]) =>
            `export const ${name.replace(/Schema$/, "JsonSchema")} = ${JSON.stringify(await exportJsonSchema(schema), null, 2)} as const;\n`,
        ),
      )
    ).join("\n"),
);
